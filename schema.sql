CREATE TABLE IF NOT EXISTS UnlucidFreeGemsLogins (
  Id INTEGER PRIMARY KEY AUTOINCREMENT,
  Login TEXT NOT NULL DEFAULT '',
  Cookie TEXT NOT NULL DEFAULT '',
  NextFreeGemsAt TEXT NOT NULL DEFAULT '1970-01-01T00:00:00.000Z',
  AuthBlocked INTEGER NOT NULL DEFAULT 0
);

CREATE INDEX IF NOT EXISTS IX_UnlucidFreeGemsLogins_NextFreeGemsAt ON UnlucidFreeGemsLogins (NextFreeGemsAt);